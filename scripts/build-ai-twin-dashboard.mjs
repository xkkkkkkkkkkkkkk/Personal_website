// Produce the single-file Dashboard deployment from the tested server sources.
import { readFile, writeFile } from 'node:fs/promises';
import vm from 'node:vm';

const base = new URL('../', import.meta.url);
const handler = await readFile(new URL('supabase/functions/ai-twin/handler.js', base), 'utf8');
const entry = await readFile(new URL('supabase/functions/ai-twin/index.ts', base), 'utf8');
const combined = '// Generated by scripts/build-ai-twin-dashboard.mjs. Paste all contents into Dashboard index.ts.\n' +
  handler.replace('export function createHandler', 'function createHandler') + '\n' +
  entry.replace(/^import \{ createHandler \} from "\.\/handler\.js";\s*/, '');
// All imports must be removed: Dashboard deployment needs only this file.
if (/^import\s/m.test(combined)) throw new Error('Unexpected import in Dashboard bundle');
new vm.Script(combined);
await writeFile(new URL('docs/ai-twin-dashboard.ts', base), combined);
console.log('Generated docs/ai-twin-dashboard.ts; syntax check passed.');
